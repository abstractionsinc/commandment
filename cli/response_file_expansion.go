var (
	errResponseFileInvalidUTF8           = errors.New("invalid UTF-8")
	errResponseFileBOMOutsideStart       = errors.New("BOM outside byte offset zero")
	errResponseFileNUL                   = errors.New("NUL in response file")
	errResponseFileTerminalBackslash     = errors.New("terminal unpaired backslash")
	errResponseFileUnterminatedQuote     = errors.New("unterminated quote")
	errResponseFileNilExpansionSession   = errors.New("nil response-file expansion session")
	errResponseFileEmptyPath             = errors.New("empty response-file path")
	errResponseFileEmptyLogicalSourceKey = errors.New("empty logical source key")
	errResponseFileContradictorySnapshot = errors.New("contradictory snapshot for logical source key")
	errInvalidResponseExpansion          = errors.New("invocation: invalid response expansion")
	errInvalidResponseIncludeAncestry    = errors.New("invocation: invalid response include ancestry")
	errInvalidResponseExpansionParent    = errors.New("invocation: invalid response expansion parent")
	errInvalidResponseExpansionCommit    = errors.New("invocation: invalid response expansion commit")
	errResponseExpansionParentOwnership  = errors.New("invocation: response expansion parent does not own argument")
	errResponseExpansionSessionOwnership = errors.New("invocation: response expansion does not belong to session")
)

const (
	defaultResponseFileDepth             = 16
	defaultResponseFileSourceBytes       = 8 << 20
	defaultResponseFileTotalSourceBytes  = 32 << 20
	defaultResponseFileTotalTokens       = 65_536
	defaultResponseFileTokenBytes        = 1 << 20
	defaultResponseFileIncludeReferences = 1_024
)

var errInvalidResponseFileLimits = errors.New("invocation: invalid response-file limits")

type responseExpansionValidationKind uint8

const (
	responseExpansionInvalidSource responseExpansionValidationKind = iota
	responseExpansionInvalidSourceIndex
	responseExpansionInvalidSpan
)

type responseExpansionValidationError struct {
	kind  responseExpansionValidationKind
	index int
}

func (err responseExpansionValidationError) Error() string {
	switch err.kind {
	case responseExpansionInvalidSource:
		return fmt.Sprintf("invocation: invalid response expansion source %d", err.index)
	case responseExpansionInvalidSourceIndex:
		return fmt.Sprintf("invocation: invalid response expansion source index %d", err.index)
	case responseExpansionInvalidSpan:
		return fmt.Sprintf("invocation: invalid response expansion span at entry %d", err.index)
	default:
		return "invocation: invalid response expansion"
	}
}

type analysisResponseFileLimits struct {
	Depth             int
	SourceBytes       int
	TotalSourceBytes  int
	TotalTokens       int
	TokenBytes        int
	IncludeReferences int
}

func normalizeResponseFileLimits(input analysisResponseFileLimits) (analysisResponseFileLimits, error) {
	values := []*int{
		&input.Depth,
		&input.SourceBytes,
		&input.TotalSourceBytes,
		&input.TotalTokens,
		&input.TokenBytes,
		&input.IncludeReferences,
	}
	defaults := []int{
		defaultResponseFileDepth,
		defaultResponseFileSourceBytes,
		defaultResponseFileTotalSourceBytes,
		defaultResponseFileTotalTokens,
		defaultResponseFileTokenBytes,
		defaultResponseFileIncludeReferences,
	}
	for i, value := range values {
		if *value < 0 {
			return analysisResponseFileLimits{}, errInvalidResponseFileLimits
		}
		if *value == 0 {
			*value = defaults[i]
		}
	}
	return input, nil
}

type responseFileSnapshot struct {
	Key         string
	Revision    string
	Location    string
	IncludeBase string
	Content     []byte
	Sensitive   bool
}

type analysisResponseFileLoad func(context.Context, string, string) (responseFileSnapshot, error)

// responseRecognition decides whether one decoded response-file lexeme is an
// include at its lexical entry boundary. Prefix contains the already-settled
// literal tokens generated by the same top-level response expansion. The
// callback may consult operation-effective canonical grammar state, but must
// not mutate Prefix.
type responseRecognition func(prefix []string, lexeme responseLexeme) (path, literal string, include bool, err error)

// responseStreamRecognition is the no-prefix-copy counterpart used when the
// caller owns an incremental canonical grammar cursor. The callback observes
// the same lexical entry boundary as ResponseRecognition; it owns advancement
// of any caller-local semantic cursor only after deciding that the lexeme is a
// literal rather than an include.
type responseStreamRecognition func(lexeme responseLexeme) (path, literal string, include bool, err error)

type responseFileErrorKind uint8

const (
	responseFileErrorInvalid responseFileErrorKind = iota
	responseFileErrorAccessUnavailable
	responseFileErrorLoad
	responseFileErrorText
	responseFileErrorSource
	responseFileErrorCycle
	responseFileErrorLimit
	responseFileErrorCancellation
)

type responseFileError struct {
	Kind  responseFileErrorKind
	Path  string
	Key   string
	Limit string
	Err   error

	source *responseFileFailureSource
}

// responseFileFailureSource is detached diagnostic source context retained from
// an acquired response snapshot. It is not accepted lexical output and does not
// commit a failed include prefix into the operation.
type responseFileFailureSource struct {
	Key       string
	Revision  string
	Location  string
	Content   []byte
	Sensitive bool
	Start     int
	End       int
}

func responseFileFailureSourceOf(err error) (responseFileFailureSource, bool) {
	responseErr, ok := errors.AsType[*responseFileError](err)
	if !ok || responseErr.source == nil {
		return responseFileFailureSource{}, false
	}
	result := *responseErr.source
	result.Content = append([]byte(nil), responseErr.source.Content...)
	return result, true
}

func (err *responseFileError) Error() string {
	if err == nil {
		return "response-file analysis failed"
	}
	switch err.Kind {
	case responseFileErrorAccessUnavailable:
		return "response-file access unavailable"
	case responseFileErrorLoad:
		return "response-file load failed"
	case responseFileErrorText:
		return "invalid response-file text"
	case responseFileErrorSource:
		return "invalid response-file source"
	case responseFileErrorCycle:
		return "response-file cycle"
	case responseFileErrorLimit:
		return "response-file limit exceeded"
	case responseFileErrorCancellation:
		return "response-file expansion canceled"
	default:
		return "response-file analysis failed"
	}
}

func (err *responseFileError) Unwrap() error {
	if err == nil {
		return nil
	}
	return err.Err
}

type responseLexeme struct {
	Text             string
	Start            int
	End              int
	escapedLeadingAt bool
}

func (lexeme responseLexeme) EscapedLeadingAt() bool { return lexeme.escapedLeadingAt }

type responseReference struct {
	Path string
	Base string
}

// recognizeResponseToken applies include-marker semantics after token decoding.
// escapedLeadingAt records private lexical escape intent from the response-file
// decoder. The returned literal is meaningful only when include is false.
func recognizeResponseToken(text string, escapedLeadingAt bool) (string, string, bool) {
	if escapedLeadingAt {
		return "", text, false
	}
	if len(text) < 2 || text[0] != '@' {
		return "", text, false
	}
	if text[1] == '@' {
		return "", text[1:], false
	}
	return text[1:], "", true
}

// recognizeResponseArgument applies the same marker semantics to a prepared
// argv token. A leading backslash is the explicit literal-at escape at this
// boundary because argv has no retained lexer escape metadata.
func recognizeResponseArgument(text string) (string, string, bool) {
	if len(text) >= 2 && text[0] == '\\' && text[1] == '@' {
		return "", text[1:], false
	}
	return recognizeResponseToken(text, false)
}

func decodeResponseFile(content []byte) ([]responseLexeme, error) {
	if !utf8.Valid(content) {
		return nil, &responseFileError{
			Kind: responseFileErrorText,
			Err:  errResponseFileInvalidUTF8,
		}
	}
	startOffset := 0
	if bytes.HasPrefix(content, []byte{0xef, 0xbb, 0xbf}) {
		startOffset = 3
	}

	var lexemes []responseLexeme
	var token []byte
	tokenStart := -1
	escapedLeadingAt := false
	quote := byte(0)
	lineOnlyWhitespace := true

	finish := func(end int) {
		if tokenStart < 0 {
			return
		}
		responseLexemeValue := responseLexeme{
			Text:             string(token),
			Start:            tokenStart,
			End:              end,
			escapedLeadingAt: escapedLeadingAt,
		}
		lexemes = append(lexemes, responseLexemeValue)
		token = token[:0]
		tokenStart = -1
		escapedLeadingAt = false
	}

	for i := startOffset; i < len(content); {
		if i != 0 && i+3 <= len(content) && bytes.Equal(content[i:i+3], []byte{0xef, 0xbb, 0xbf}) {
			return nil, &responseFileError{
				Kind: responseFileErrorText,
				Err:  errResponseFileBOMOutsideStart,
			}
		}
		r, size := utf8.DecodeRune(content[i:])
		if r == 0 {
			return nil, &responseFileError{
				Kind: responseFileErrorText,
				Err:  errResponseFileNUL,
			}
		}

		switch {
		case quote == '\'':
			if r == '\'' {
				quote = 0
				lineOnlyWhitespace = false
				i += size
				continue
			}
			if tokenStart < 0 {
				tokenStart = i
			}
			token = append(token, content[i:i+size]...)
			if r == '\n' || r == '\r' {
				if r == '\r' && i+size < len(content) && content[i+size] == '\n' {
					token = append(token, '\n')
					i++
				}
				lineOnlyWhitespace = true
			} else {
				lineOnlyWhitespace = false
			}
			i += size
			continue
		case r == '\\':
			if tokenStart < 0 {
				tokenStart = i
			}
			next := i + size
			if next >= len(content) {
				return nil, &responseFileError{
					Kind: responseFileErrorText,
					Err:  errResponseFileTerminalBackslash,
				}
			}
			nextRune, nextSize := utf8.DecodeRune(content[next:])
			if nextRune == '\r' || nextRune == '\n' {
				if nextRune == '\r' && next+nextSize < len(content) && content[next+nextSize] == '\n' {
					nextSize++
				}
				i = next + nextSize
				lineOnlyWhitespace = true
				continue
			}
			if len(token) == 0 && nextRune == '@' {
				escapedLeadingAt = true
			}
			token = append(token, content[next:next+nextSize]...)
			lineOnlyWhitespace = false
			i = next + nextSize
			continue
		case quote == '"':
			if r == '"' {
				quote = 0
				lineOnlyWhitespace = false
				i += size
				continue
			}
			if tokenStart < 0 {
				tokenStart = i
			}
			token = append(token, content[i:i+size]...)
			if r == '\n' || r == '\r' {
				if r == '\r' && i+size < len(content) && content[i+size] == '\n' {
					token = append(token, '\n')
					i++
				}
				lineOnlyWhitespace = true
			} else {
				lineOnlyWhitespace = false
			}
			i += size
			continue
		}

		switch r {
		case '\'', '"':
			if tokenStart < 0 {
				tokenStart = i
			}
			quote = content[i]
			lineOnlyWhitespace = false
			i += size
		case '#':
			if lineOnlyWhitespace {
				finish(i)
				for i < len(content) {
					r, size = utf8.DecodeRune(content[i:])
					if r == '\n' {
						i += size
						break
					}
					if r == '\r' {
						i += size
						if i < len(content) && content[i] == '\n' {
							i++
						}
						break
					}
					i += size
				}
				lineOnlyWhitespace = true
				continue
			}
			if tokenStart < 0 {
				tokenStart = i
			}
			token = append(token, '#')
			lineOnlyWhitespace = false
			i += size
		case ' ', '\t':
			finish(i)
			i += size
		case '\n', '\r':
			finish(i)
			if r == '\r' && i+size < len(content) && content[i+size] == '\n' {
				i++
			}
			i += size
			lineOnlyWhitespace = true
		default:
			if tokenStart < 0 {
				tokenStart = i
			}
			token = append(token, content[i:i+size]...)
			lineOnlyWhitespace = false
			i += size
		}
	}
	if quote != 0 {
		return nil, &responseFileError{
			Kind: responseFileErrorText,
			Err:  errResponseFileUnterminatedQuote,
		}
	}
	finish(len(content))
	return lexemes, nil
}

