// responseFileSession owns response-file snapshot identity and
// aggregate budgets across the accepted frames of one frontend operation.
// Frames are staged independently and enter this state only through Commit.
type responseFileSession struct {
	limits analysisResponseFileLimits

	sourceByKey  map[string]responseFileSnapshot
	uniqueBytes  int
	tokenCount   int
	includeCount int
}

type responseExpansionState struct {
	load            analysisResponseFileLoad
	session         *responseFileSession
	recognize       responseRecognition
	streamRecognize responseStreamRecognition
	prefix          []string

	sources     []responseExpansionSource
	sourceByKey map[string]int
	active      map[string]struct{}
	entries     []responseExpansionEntry

	pendingByKey map[string]responseFileSnapshot
	uniqueBytes  int
	tokenCount   int
	includeCount int
}

// prepareResponseFileSession creates one empty operation-lifetime
// response-file accounting session.
func prepareResponseFileSession(limits analysisResponseFileLimits) (*responseFileSession, error) {
	normalized, err := normalizeResponseFileLimits(limits)
	if err != nil {
		return nil, err
	}
	return &responseFileSession{
		limits:      normalized,
		sourceByKey: make(map[string]responseFileSnapshot),
	}, nil
}

// Stage expands one speculative top-level response frame against the session's
// already accepted snapshots and budgets without mutating the session.
func (session *responseFileSession) Stage(ctx context.Context, load analysisResponseFileLoad, reference responseReference) (responseExpansion, error) {
	return session.StageWithRecognition(ctx, load, reference, nil)
}

// StageWithRecognition is Stage with grammar-aware response recognition.
func (session *responseFileSession) StageWithRecognition(ctx context.Context, load analysisResponseFileLoad, reference responseReference, recognize responseRecognition) (responseExpansion, error) {
	return session.stageWithRecognizers(ctx, load, reference, recognize, nil)
}

// StageWithStreamRecognition stages one response frame without materializing a
// detached growing prefix for every lexical callback. It is intended for a
// caller that advances the canonical grammar scanner incrementally.
func (session *responseFileSession) StageWithStreamRecognition(ctx context.Context, load analysisResponseFileLoad, reference responseReference, recognize responseStreamRecognition) (responseExpansion, error) {
	return session.stageWithRecognizers(ctx, load, reference, nil, recognize)
}

func (session *responseFileSession) stageWithRecognizers(ctx context.Context, load analysisResponseFileLoad, reference responseReference, recognize responseRecognition, streamRecognize responseStreamRecognition) (responseExpansion, error) {
	if session == nil {
		return responseExpansion{}, &responseFileError{
			Kind: responseFileErrorInvalid,
			Err:  errResponseFileNilExpansionSession,
		}
	}
	if ctx == nil {
		return responseExpansion{}, &responseFileError{
			Kind: responseFileErrorCancellation,
			Err:  context.Canceled,
		}
	}
	if reference.Path == "" {
		return responseExpansion{}, &responseFileError{
			Kind: responseFileErrorInvalid,
			Err:  errResponseFileEmptyPath,
		}
	}
	if load == nil {
		return responseExpansion{}, &responseFileError{
			Kind: responseFileErrorAccessUnavailable,
			Path: reference.Path,
		}
	}
	state := &responseExpansionState{
		load:            load,
		session:         session,
		recognize:       recognize,
		streamRecognize: streamRecognize,
		sourceByKey:     make(map[string]int),
		active:          make(map[string]struct{}),
		pendingByKey:    make(map[string]responseFileSnapshot),
		uniqueBytes:     session.uniqueBytes,
		tokenCount:      session.tokenCount,
		includeCount:    session.includeCount,
	}
	if err := state.expand(ctx, reference.Path, reference.Base, 1, -1); err != nil {
		return responseExpansion{}, err
	}
	pending := make(map[string]responseFileSnapshot, len(state.pendingByKey))
	for key, snapshot := range state.pendingByKey {
		pending[key] = cloneResponseSnapshot(snapshot)
	}
	result := responseExpansion{
		sources: append([]responseExpansionSource(nil), state.sources...),
		entries: append([]responseExpansionEntry(nil), state.entries...),
		commit: &responseExpansionSessionCommit{
			session:      session,
			sourceByKey:  pending,
			uniqueBytes:  state.uniqueBytes,
			tokenCount:   state.tokenCount,
			includeCount: state.includeCount,
		},
	}
	return result, nil
}

// commit accepts one successfully staged response frame into the operation
// session. The caller must commit canonical operation argv/source/origin state
// before calling Commit; rejected frames are discarded by omitting this call.
func (session *responseFileSession) commit(expansion responseExpansion) {
	commit := expansion.commit
	if session == nil || commit == nil || commit.session != session || commit.committed {
		panic("invocation: invalid response-file expansion session commit")
	}
	for key, snapshot := range commit.sourceByKey {
		session.sourceByKey[key] = cloneResponseSnapshot(snapshot)
	}
	session.uniqueBytes = commit.uniqueBytes
	session.tokenCount = commit.tokenCount
	session.includeCount = commit.includeCount
	commit.committed = true
}

func (state *responseExpansionState) expand(ctx context.Context, path, base string, depth, parentInclude int) error {
	if err := state.checkCancellation(ctx, path); err != nil {
		return err
	}
	state.includeCount++
	if state.includeCount > state.session.limits.IncludeReferences {
		return state.limitError(path, "include-references")
	}
	if depth > state.session.limits.Depth {
		return state.limitError(path, "depth")
	}

	snapshot, err := state.load(ctx, path, base)
	if err != nil {
		if cancellation := state.cancellationError(ctx, path); cancellation != nil {
			return cancellation
		}
		result := &responseFileError{
			Kind: responseFileErrorLoad,
			Path: path,
			Err:  err,
		}

		return result
	}
	snapshot = cloneResponseSnapshot(snapshot)
	if err := state.checkCancellation(ctx, path); err != nil {
		return err
	}
	if snapshot.Key == "" {
		result := &responseFileError{
			Kind: responseFileErrorSource,
			Path: path,
			Err:  errResponseFileEmptyLogicalSourceKey,
		}

		return result
	}
	if len(snapshot.Content) > state.session.limits.SourceBytes {
		return state.limitError(path, "source-bytes")
	}
	if _, cycle := state.active[snapshot.Key]; cycle {
		result := &responseFileError{
			Kind: responseFileErrorCycle,
			Path: path,
			Key:  snapshot.Key,
		}

		return result
	}

	sourceIndex, existing := state.sourceByKey[snapshot.Key]
	switch {
	case existing:
		if !sameResponseSnapshot(state.sources[sourceIndex].snapshot, snapshot) {
			result := &responseFileError{
				Kind: responseFileErrorSource,
				Path: path,
				Key:  snapshot.Key,
				Err:  errResponseFileContradictorySnapshot,
			}

			return result
		}
	default:
		accepted, acceptedBeforeFrame := state.session.sourceByKey[snapshot.Key]
		if acceptedBeforeFrame && !sameResponseSnapshot(accepted, snapshot) {
			result := &responseFileError{
				Kind: responseFileErrorSource,
				Path: path,
				Key:  snapshot.Key,
				Err:  errResponseFileContradictorySnapshot,
			}

			return result
		}
		if !acceptedBeforeFrame {
			state.uniqueBytes += len(snapshot.Content)
			if state.uniqueBytes > state.session.limits.TotalSourceBytes {
				return state.limitError(path, "total-source-bytes")
			}
			state.pendingByKey[snapshot.Key] = snapshot
		}
		copySnapshot := snapshot
		revision := copySnapshot.Revision
		if revision == "" {
			revision = exactContentRevision(copySnapshot.Content)
		}
		sourceIndex = len(state.sources)
		state.sources = append(state.sources, responseExpansionSource{
			snapshot: copySnapshot,
			revision: revision,
		})
		state.sourceByKey[copySnapshot.Key] = sourceIndex
	}

	state.active[snapshot.Key] = struct{}{}
	defer delete(state.active, snapshot.Key)

	lexemes, err := decodeResponseFile(snapshot.Content)
	if err != nil {
		if responseErr, ok := errors.AsType[*responseFileError](err); ok {
			responseErr.Path = path
			responseErr.Key = snapshot.Key
		}
		state.attachFailureSource(err, sourceIndex, 0, len(snapshot.Content))
		return err
	}
	for _, lexeme := range lexemes {
		if err := state.checkCancellation(ctx, path); err != nil {
			return err
		}
		childPath, literal, include, err := state.recognizeLexeme(lexeme)
		if err != nil {
			state.attachFailureSource(err, sourceIndex, lexeme.Start, lexeme.End)
			return err
		}
		if include {
			entryIndex := len(state.entries)
			entry := responseExpansionEntry{
				sourceIndex:   sourceIndex,
				start:         lexeme.Start,
				end:           lexeme.End,
				text:          childPath,
				spelling:      lexeme.Text,
				include:       true,
				parentInclude: parentInclude,
			}
			state.entries = append(state.entries, entry)
			if err := state.expand(ctx, childPath, snapshot.IncludeBase, depth+1, entryIndex); err != nil {
				state.attachFailureSource(err, sourceIndex, lexeme.Start, lexeme.End)
				return err
			}
			continue
		}
		if len(literal) > state.session.limits.TokenBytes {
			err := state.limitError(path, "token-bytes")
			state.attachFailureSource(err, sourceIndex, lexeme.Start, lexeme.End)
			return err
		}
		state.tokenCount++
		if state.tokenCount > state.session.limits.TotalTokens {
			err := state.limitError(path, "total-tokens")
			state.attachFailureSource(err, sourceIndex, lexeme.Start, lexeme.End)
			return err
		}
		entry2 := responseExpansionEntry{
			sourceIndex:   sourceIndex,
			start:         lexeme.Start,
			end:           lexeme.End,
			text:          literal,
			parentInclude: parentInclude,
		}
		state.entries = append(state.entries, entry2)
		if state.streamRecognize == nil {
			state.prefix = append(state.prefix, literal)
		}
	}
	return nil
}

func (state *responseExpansionState) recognizeLexeme(lexeme responseLexeme) (string, string, bool, error) {
	if state.streamRecognize != nil {
		return state.streamRecognize(lexeme)
	}
	if state.recognize == nil {
		path, literal, include := recognizeResponseToken(lexeme.Text, lexeme.escapedLeadingAt)
		return path, literal, include, nil
	}
	prefix := append([]string(nil), state.prefix...)
	return state.recognize(prefix, lexeme)
}

func (state *responseExpansionState) attachFailureSource(err error, sourceIndex, start, end int) {
	responseErr, ok := errors.AsType[*responseFileError](err)
	if !ok || responseErr.source != nil || sourceIndex < 0 ||
		sourceIndex >= len(state.sources) {
		return
	}
	source := state.sources[sourceIndex]
	if start < 0 || end < start || end > len(source.snapshot.Content) {
		return
	}
	responseErr.source = &responseFileFailureSource{
		Key:       source.snapshot.Key,
		Revision:  source.revision,
		Location:  source.snapshot.Location,
		Content:   append([]byte(nil), source.snapshot.Content...),
		Sensitive: source.snapshot.Sensitive,
		Start:     start,
		End:       end,
	}
}

func (state *responseExpansionState) checkCancellation(ctx context.Context, path string) error {
	select {
	case <-ctx.Done():
		cause := context.Cause(ctx)
		if cause == nil {
			cause = ctx.Err()
		}
		result := &responseFileError{
			Kind: responseFileErrorCancellation,
			Path: path,
			Err:  cause,
		}

		return result
	default:
		return nil
	}
}

func (state *responseExpansionState) cancellationError(ctx context.Context, path string) error {
	if ctx.Err() == nil {
		return nil
	}
	cause := context.Cause(ctx)
	if cause == nil {
		cause = ctx.Err()
	}
	result := &responseFileError{
		Kind: responseFileErrorCancellation,
		Path: path,
		Err:  cause,
	}

	return result
}

func (state *responseExpansionState) limitError(path, limit string) error {
	result := &responseFileError{
		Kind:  responseFileErrorLimit,
		Path:  path,
		Limit: limit,
	}

	return result
}

func cloneResponseSnapshot(snapshot responseFileSnapshot) responseFileSnapshot {
	clone := snapshot
	clone.Content = append([]byte(nil), snapshot.Content...)
	return clone
}

func sameResponseSnapshot(left, right responseFileSnapshot) bool {
	return left.Key == right.Key &&
		left.Revision == right.Revision &&
		left.Location == right.Location &&
		left.IncludeBase == right.IncludeBase &&
		left.Sensitive == right.Sensitive &&
		bytes.Equal(left.Content, right.Content)
}

func exactContentRevision(content []byte) string {
	digest := sha256.Sum256(content)
	return "sha256:" + hex.EncodeToString(digest[:])
}

func (expansion responseExpansion) Valid() bool {
	return len(expansion.sources) > 0
}

// TokenTexts returns the detached flattened token text produced by a staged
// expansion. It exposes no source/origin identity and does not commit the
// expansion session; Completion uses it only for speculative grammar branches.
func (expansion responseExpansion) TokenTexts() []string {
	if !expansion.Valid() {
		return nil
	}
	result := make([]string, 0, len(expansion.entries))
	for _, entry := range expansion.entries {
		if entry.include {
			continue
		}
		result = append(result, entry.text)
	}
	return result
}

func validateResponseExpansion(expansion responseExpansion) error {
	if !expansion.Valid() {
		return errInvalidResponseExpansion
	}
	for index, source := range expansion.sources {
		if source.snapshot.Key == "" || source.revision == "" {
			return responseExpansionValidationError{
				kind:  responseExpansionInvalidSource,
				index: index,
			}
		}
	}
	for index, entry := range expansion.entries {
		if entry.sourceIndex < 0 || entry.sourceIndex >= len(expansion.sources) {
			return responseExpansionValidationError{
				kind:  responseExpansionInvalidSourceIndex,
				index: entry.sourceIndex,
			}
		}
		if entry.start < 0 || entry.end < entry.start ||
			entry.end > len(expansion.sources[entry.sourceIndex].snapshot.Content) {
			return responseExpansionValidationError{
				kind:  responseExpansionInvalidSpan,
				index: index,
			}
		}
		if entry.parentInclude >= 0 {
			if entry.parentInclude >= index || !expansion.entries[entry.parentInclude].include {
				return errInvalidResponseIncludeAncestry
			}
		}
	}
	return nil
}

func (analysis *analysisState) commitResponseExpansionProvenance(operation *invocation, expansion responseExpansion, parent originRef) (committedResponseExpansion, error) {
	if operation == nil || !expansion.Valid() {
		return committedResponseExpansion{}, errInvalidResponseExpansion
	}
	if parent.operation != operation || !parent.id.present() || !analysis.hasOrigin(parent.id) {
		return committedResponseExpansion{}, errInvalidResponseExpansionParent
	}

	if err := validateResponseExpansion(expansion); err != nil {
		return committedResponseExpansion{}, err
	}

	sourceRefs := make([]sourceRef, len(expansion.sources))
	for index, source := range expansion.sources {
		sourceRefs[index] = analysis.addResponseSource(operation,
			source.snapshot.Key,
			source.revision,
			source.snapshot.Location,
			source.snapshot.IncludeBase,
			source.snapshot.Sensitive,
		)
	}

	includeOrigins := make(map[int]originRef)
	committed := committedResponseExpansion{}
	for index, entry := range expansion.entries {
		parents := []originRef{parent}
		if entry.parentInclude >= 0 {
			includeParent, ok := includeOrigins[entry.parentInclude]
			if !ok {
				return committedResponseExpansion{}, errInvalidResponseIncludeAncestry
			}
			parents = []originRef{includeParent}
		}
		sensitive := expansion.sources[entry.sourceIndex].snapshot.Sensitive || analysis.originSensitive(parents[0].id)
		spanRefValue := spanRef{
			Source: sourceRefs[entry.sourceIndex],
			Entry:  -1,
			Start:  entry.start,
			End:    entry.end,
		}
		origin := analysis.addOrigin(operation, spanRefValue, parents, sensitive)
		entry2 := committedResponseEntry{
			Text:     entry.text,
			Spelling: entry.spelling,
			Origin:   origin,
			Include:  entry.include,
		}
		committed.Entries = append(committed.Entries, entry2)
		if entry.include {
			includeOrigins[index] = origin
			responseIncludeValue := responseInclude{
				Path:     entry.text,
				Spelling: entry.spelling,
				Origin:   origin,
				Role:     tokenRoleResponseFile,
			}
			committed.Includes = append(committed.Includes, responseIncludeValue)
			continue
		}
		committed.Tokens = append(committed.Tokens, responseExpandedToken{
			Text:   entry.text,
			Origin: origin,
		})
	}
	return committed, nil
}

// CommitResponseExpansion commits a staged response-file frame as one
// operation-owned transition. Provenance, argv, include observations, and the
// operation-lifetime response budget/session advance together or not at all.
func (operation *invocation) CommitResponseExpansion(index int, spelling string, expansion responseExpansion, parent originRef, session *responseFileSession) (int, error) {
	return operation.analysis.commitResponseExpansion(operation, index, spelling, expansion, parent, session)
}

func (analysis *analysisState) commitResponseExpansion(operation *invocation, index int, spelling string, expansion responseExpansion, parent originRef, session *responseFileSession) (int, error) {
	if operation == nil || index < 0 || index >= len(analysis.args) || spelling == "" || session == nil {
		return 0, errInvalidResponseExpansionCommit
	}
	if parent.operation != operation || !parent.id.present() || analysis.provenance.argumentOrigins[index].id != parent.id {
		return 0, errResponseExpansionParentOwnership
	}
	if expansion.commit == nil || expansion.commit.session != session || expansion.commit.committed {
		return 0, errResponseExpansionSessionOwnership
	}
	if err := validateResponseExpansion(expansion); err != nil {
		return 0, err
	}

	// After the complete preflight above, the remaining helpers operate only on
	// identities created from this operation and on a session proven to own the
	// staged frame. They therefore cannot reject independently.
	committed, err := analysis.commitResponseExpansionProvenance(operation, expansion, parent)
	if err != nil {
		return 0, err
	}
	if err := analysis.spliceResponseExpansion(operation, index, spelling, committed); err != nil {
		panic("invocation: response commit preflight invariant: " + err.Error())
	}
	session.commit(expansion)
	return len(committed.Tokens), nil
}

type responseArgumentExpansionError struct {
	argument  int
	prefix    grammarPrefixResult
	hasPrefix bool
	err       error
}

func (err *responseArgumentExpansionError) Error() string {
	if err == nil || err.err == nil {
		return "response argument expansion failed"
	}
	return err.err.Error()
}

func (err *responseArgumentExpansionError) Unwrap() error {
	if err == nil {
		return nil
	}
	return err.err
}

func responseExpansionFailureArgument(err error) (int, bool) {
	expansionErr, ok := errors.AsType[*responseArgumentExpansionError](err)
	if !ok || expansionErr.argument < 0 {
		return 0, false
	}
	return expansionErr.argument, true
}

func responseExpansionFailurePrefix(err error) (grammarPrefixResult, bool) {
	expansionErr, ok := errors.AsType[*responseArgumentExpansionError](err)
	if !ok || !expansionErr.hasPrefix {
		return grammarPrefixResult{}, false
	}
	return expansionErr.prefix, true
}

// settleResponseRange consumes complete response inclusions through the same
// operation-local grammar frontier that recognizes ordinary committed input.
// It mutates only the supplied analysis snapshot; an authoritative include is
// first applied to a full child snapshot and then published atomically.
func settleResponseRange(ctx context.Context, operation *invocation, analysis *analysisState, start, stopBefore, skipArgument int) (int, error) {
	cursor := stopBefore
	if operation == nil || analysis == nil || analysis.responses == nil {
		panic("cli: response settlement requires active analysis")
	}
	if start < 0 || start > len(analysis.args) || (cursor >= 0 && start > cursor) {
		panic("cli: response settlement range is invalid")
	}

	grammarCursor := prepareOperationGrammarPrefixCursorAt(
		ctx,
		operation,
		analysis,
		start,
		skipArgument,
		operation.namespaceForAt(ctx, analysis),
		operation.conditionForAt(ctx, analysis),
		operation.defaultCommandForAt(ctx, analysis),
	)

	for index := start; ; {
		limit := len(analysis.args)
		if cursor >= 0 {
			limit = cursor
		}
		if index >= limit {
			return cursor, nil
		}
		if !grammarCursor.Ready() {
			return cursor, nil
		}

		dialect, ok := grammarCursor.Dialect()
		if index < 0 || index >= len(analysis.args) {
			panic("cli: response settlement index escaped analysis input")
		}
		argument := analysis.args[index]
		if !ok || !dialect.ResponseFiles() {
			grammarCursor.Append(ctx, argument)
			index++
			continue
		}

		path, literal, include := recognizeResponseArgument(argument)
		if !include {
			if literal != argument {
				if err := analysis.rewriteArgument(index, literal); err != nil {
					return cursor, &responseArgumentExpansionError{
						argument: index,
						err:      err,
					}
				}
			}
			grammarCursor.Append(ctx, literal)
			index++
			continue
		}

		parent, ok := analysis.argumentOrigin(index)
		if !ok {
			panic("cli: response include has no committed input origin")
		}

		authoritative := operation.analysis == analysis
		if !authoritative {
			expansion, err := stageResponseExpansion(ctx, operation, analysis, grammarCursor, path)
			if err != nil {
				return cursor, &responseArgumentExpansionError{
					argument: index,
					err:      err,
				}
			}
			produced, err := analysis.commitResponseExpansion(operation, index, argument, expansion, parent, analysis.responses)
			if err != nil {
				return cursor, &responseArgumentExpansionError{
					argument: index,
					err:      err,
				}
			}
			grammarCursor.RefreshCommittedOrigins()
			if cursor >= 0 {
				cursor += produced - 1
			}
			index += produced
			continue
		}

		prefix := grammarCursor.Prefix(ctx)
		child := analysis.forkResponse(operation)
		childCursor := prepareOperationGrammarPrefixCursorAt(
			ctx,
			operation,
			child,
			index,
			skipArgument,
			operation.namespaceForAt(ctx, child),
			operation.conditionForAt(ctx, child),
			operation.defaultCommandForAt(ctx, child),
		)
		expansion, err := stageResponseExpansion(ctx, operation, child, childCursor, path)
		if err != nil {
			return cursor, &responseArgumentExpansionError{
				argument:  index,
				prefix:    prefix,
				hasPrefix: true,
				err:       err,
			}
		}
		childParent, ok := child.argumentOrigin(index)
		if !ok {
			panic("cli: response child include has no committed input origin")
		}
		produced, err := child.commitResponseExpansion(operation, index, argument, expansion, childParent, child.responses)
		if err != nil {
			return cursor, &responseArgumentExpansionError{
				argument:  index,
				prefix:    prefix,
				hasPrefix: true,
				err:       err,
			}
		}
		operation.publishResponse(prepareResponseCommit(analysis, child))

		analysis = child
		if cursor >= 0 {
			cursor += produced - 1
		}
		index += produced
		grammarCursor = prepareOperationGrammarPrefixCursorAt(
			ctx,
			operation,
			child,
			index,
			skipArgument,
			operation.namespaceForAt(ctx, child),
			operation.conditionForAt(ctx, child),
			operation.defaultCommandForAt(ctx, child),
		)
	}
}

func stageResponseExpansion(ctx context.Context, operation *invocation, analysis *analysisState, grammarCursor *grammarPrefixCursor, path string) (responseExpansion, error) {
	return analysis.responses.StageWithStreamRecognition(
		ctx,
		responseFileLoad(operation.input.responseFiles),
		responseReference{
			Path: path,
			Base: operation.input.workingDirectory,
		},
		func(lexeme responseLexeme) (string, string, bool, error) {
			if !grammarCursor.Ready() {
				grammarCursor.Append(ctx, lexeme.Text)
				return "", lexeme.Text, false, nil
			}
			selectedDialect, dialectOK := grammarCursor.Dialect()
			if !dialectOK || !selectedDialect.ResponseFiles() {
				grammarCursor.Append(ctx, lexeme.Text)
				return "", lexeme.Text, false, nil
			}
			childPath, childLiteral, childInclude := recognizeResponseToken(lexeme.Text, lexeme.EscapedLeadingAt())
			if !childInclude {
				grammarCursor.Append(ctx, childLiteral)
			}
			return childPath, childLiteral, childInclude, nil
		},
	)
}
